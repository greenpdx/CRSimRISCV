//! Plain-English descriptions for RISC-V instruction mnemonics.
//! Used as the disassembler's `desc` field for tooltip display.

#[allow(dead_code)]
pub fn mnemonic_desc(m: &str) -> Option<&'static str> {
    Some(match m {
        // ── RV32I base ─────────────────────────────────────────────────
        "NOP"   => "No-op (canonical addi x0, x0, 0).",
        "ADD"   => "rd = rs1 + rs2.",
        "SUB"   => "rd = rs1 - rs2.",
        "AND"   => "rd = rs1 & rs2 (bitwise AND).",
        "OR"    => "rd = rs1 | rs2 (bitwise OR).",
        "XOR"   => "rd = rs1 ^ rs2 (bitwise XOR).",
        "SLL"   => "rd = rs1 << (rs2 & 0x1f) (shift left logical).",
        "SRL"   => "rd = rs1 >> (rs2 & 0x1f) (shift right logical, zero fill).",
        "SRA"   => "rd = rs1 >> (rs2 & 0x1f) (shift right arithmetic, sign fill).",
        "SLT"   => "rd = (rs1 < rs2 signed) ? 1 : 0.",
        "SLTU"  => "rd = (rs1 < rs2 unsigned) ? 1 : 0.",
        "ADDI"  => "rd = rs1 + sign-extended 12-bit immediate.",
        "ANDI"  => "rd = rs1 & sign-extended imm.",
        "ORI"   => "rd = rs1 | sign-extended imm.",
        "XORI"  => "rd = rs1 ^ sign-extended imm.",
        "SLLI"  => "rd = rs1 << shamt (logical left).",
        "SRLI"  => "rd = rs1 >> shamt (logical right).",
        "SRAI"  => "rd = rs1 >> shamt (arithmetic right).",
        "SLTI"  => "rd = (rs1 < imm signed) ? 1 : 0.",
        "SLTIU" => "rd = (rs1 < imm unsigned) ? 1 : 0.",
        "LB"    => "rd = sign-extended byte at MEM[rs1 + imm].",
        "LH"    => "rd = sign-extended half (16-bit) at MEM[rs1 + imm].",
        "LW"    => "rd = word (32-bit) at MEM[rs1 + imm].",
        "LBU"   => "rd = zero-extended byte at MEM[rs1 + imm].",
        "LHU"   => "rd = zero-extended half at MEM[rs1 + imm].",
        "SB"    => "MEM[rs1 + imm] = rs2[7:0] (store byte).",
        "SH"    => "MEM[rs1 + imm] = rs2[15:0] (store half).",
        "SW"    => "MEM[rs1 + imm] = rs2 (store word).",
        "BEQ"   => "if rs1 == rs2: pc += sign-extended branch offset.",
        "BNE"   => "if rs1 != rs2: pc += sign-extended branch offset.",
        "BLT"   => "if rs1 <  rs2 (signed): branch.",
        "BGE"   => "if rs1 >= rs2 (signed): branch.",
        "BLTU"  => "if rs1 <  rs2 (unsigned): branch.",
        "BGEU"  => "if rs1 >= rs2 (unsigned): branch.",
        "LUI"   => "rd = imm << 12 (load upper immediate).",
        "AUIPC" => "rd = pc + (imm << 12) (PC-relative upper immediate).",
        "JAL"   => "rd = pc + 4; pc += sign-extended J-imm. Used for direct calls.",
        "JALR"  => "rd = pc + 4; pc = (rs1 + imm) & ~1. Used for indirect calls / returns.",
        // ── Privileged / system ────────────────────────────────────────
        "ECALL"  => "Environment call. Traps to the next privilege level (U→M, S→M, etc.).",
        "EBREAK" => "Environment breakpoint. Raises a breakpoint exception (debugger entry).",
        "MRET"   => "Machine-mode return. Restores PC from mepc, mode from mstatus.MPP, MIE from MPIE.",
        "SRET"   => "Supervisor-mode return. Restores PC from sepc, mode from SPP, SIE from SPIE.",
        "WFI"    => "Wait for interrupt. Stalls the hart until an interrupt is pending.",
        "SFENCE.VMA" => "Synchronize updates to the page tables on the current hart.",
        // ── Zicsr ──────────────────────────────────────────────────────
        "CSRRW"  => "rd = csr; csr = rs1 (atomic read-write).",
        "CSRRS"  => "rd = csr; csr |=  rs1 (atomic read and set bits).",
        "CSRRC"  => "rd = csr; csr &= ~rs1 (atomic read and clear bits).",
        "CSRRWI" => "rd = csr; csr = uimm[4:0].",
        "CSRRSI" => "rd = csr; csr |=  uimm[4:0].",
        "CSRRCI" => "rd = csr; csr &= ~uimm[4:0].",
        // ── MISC-MEM ───────────────────────────────────────────────────
        "FENCE"   => "Memory ordering barrier. pred,succ specify which memory ops to order.",
        "FENCE.I" => "Instruction-fetch fence. Synchronizes I-cache after self-modifying code.",
        "PAUSE"   => "Hint to the hardware that this hart is in a busy-wait loop.",
        // ── M extension ────────────────────────────────────────────────
        "MUL"    => "rd = (rs1 * rs2) low 32 bits.",
        "MULH"   => "rd = (rs1 * rs2) high 32 bits, both signed.",
        "MULHSU" => "rd = high 32 bits of (signed rs1 * unsigned rs2).",
        "MULHU"  => "rd = high 32 bits of (unsigned * unsigned).",
        "DIV"    => "rd = rs1 / rs2 (signed). Division by zero returns -1, no trap.",
        "DIVU"   => "rd = rs1 / rs2 (unsigned). Division by zero returns 2^32-1.",
        "REM"    => "rd = rs1 % rs2 (signed). Remainder of DIV.",
        "REMU"   => "rd = rs1 % rs2 (unsigned).",
        // ── A extension ────────────────────────────────────────────────
        "LR.W"     => "Load-reserved word. Reads MEM[rs1] and registers a reservation.",
        "SC.W"     => "Store-conditional word. Writes only if the reservation is still valid; rd=0 on success.",
        "AMOSWAP.W" => "Atomic swap: temp = MEM[rs1]; MEM[rs1] = rs2; rd = temp.",
        "AMOADD.W"  => "Atomic add:  rd = MEM[rs1]; MEM[rs1] = rd + rs2.",
        "AMOXOR.W"  => "Atomic XOR.",
        "AMOAND.W"  => "Atomic AND.",
        "AMOOR.W"   => "Atomic OR.",
        "AMOMIN.W"  => "Atomic signed minimum.",
        "AMOMAX.W"  => "Atomic signed maximum.",
        "AMOMINU.W" => "Atomic unsigned minimum.",
        "AMOMAXU.W" => "Atomic unsigned maximum.",
        // ── Zba ────────────────────────────────────────────────────────
        "SH1ADD" => "rd = (rs1 << 1) + rs2 (address-gen helper).",
        "SH2ADD" => "rd = (rs1 << 2) + rs2.",
        "SH3ADD" => "rd = (rs1 << 3) + rs2.",
        // ── Zbb ────────────────────────────────────────────────────────
        "ANDN"   => "rd = rs1 & ~rs2 (and-not).",
        "ORN"    => "rd = rs1 | ~rs2 (or-not).",
        "XNOR"   => "rd = ~(rs1 ^ rs2).",
        "MIN"    => "rd = signed min(rs1, rs2).",
        "MAX"    => "rd = signed max(rs1, rs2).",
        "MINU"   => "rd = unsigned min.",
        "MAXU"   => "rd = unsigned max.",
        "ROL"    => "rd = rotate-left rs1 by (rs2 & 0x1f).",
        "ROR"    => "rd = rotate-right rs1 by (rs2 & 0x1f).",
        "RORI"   => "rd = rotate-right rs1 by shamt.",
        "ZEXT.H" => "rd = rs1 with high 16 bits zeroed.",
        "CLZ"    => "rd = count of leading zeros in rs1.",
        "CTZ"    => "rd = count of trailing zeros in rs1.",
        "CPOP"   => "rd = popcount of rs1 (number of 1 bits).",
        "SEXT.B" => "rd = sign-extend rs1[7:0].",
        "SEXT.H" => "rd = sign-extend rs1[15:0].",
        "ORC.B"  => "Per-byte OR-combine: each byte becomes 0xff if any bit set, else 0.",
        "REV8"   => "Byte reverse rs1 (endianness flip).",
        // ── Zbc / Zbs ──────────────────────────────────────────────────
        "CLMUL"  => "Carry-less multiply low.",
        "CLMULH" => "Carry-less multiply high.",
        "CLMULR" => "Carry-less multiply reversed.",
        "BCLR"   => "Clear bit rs2 in rs1.",
        "BEXT"   => "Extract bit rs2 from rs1 into bit 0 of rd.",
        "BINV"   => "Invert bit rs2 in rs1.",
        "BSET"   => "Set bit rs2 in rs1.",
        "BCLRI"  => "Clear bit shamt in rs1.",
        "BEXTI"  => "Extract bit shamt from rs1.",
        "BINVI"  => "Invert bit shamt in rs1.",
        "BSETI"  => "Set bit shamt in rs1.",
        // ── F / D / Q / Zfh — show common ones; the rest fall through ──
        "FLW"   => "Load 32-bit float from memory into FP register.",
        "FSW"   => "Store 32-bit float to memory.",
        "FLD"   => "Load 64-bit double.",
        "FSD"   => "Store 64-bit double.",
        "FADD.S" => "Single-precision add: rd = rs1 + rs2.",
        "FSUB.S" => "Single-precision subtract.",
        "FMUL.S" => "Single-precision multiply.",
        "FDIV.S" => "Single-precision divide.",
        "FSQRT.S" => "Single-precision square root.",
        "FMADD.S" => "Fused multiply-add: rd = (rs1 * rs2) + rs3 (single).",
        "FMV.W.X" => "Move 32-bit integer bit pattern into an FP register (no conversion).",
        "FMV.X.W" => "Move FP register bit pattern to integer register.",
        "FCVT.W.S" => "Convert single-precision float to signed 32-bit integer.",
        "FCVT.S.W" => "Convert signed 32-bit integer to single-precision float.",
        "FCLASS.S" => "Classify FP value: bit per category (negative, zero, NaN, infinity, ...).",
        "FADD.D" => "Double-precision add.",
        "FMUL.D" => "Double-precision multiply.",
        // ── Compressed ──────────────────────────────────────────────────
        "C.NOP"      => "Compressed no-op.",
        "C.ADDI"     => "Compressed add immediate.",
        "C.LI"       => "Compressed load immediate (sign-extended 6-bit).",
        "C.LUI"      => "Compressed LUI.",
        "C.MV"       => "Compressed move register-to-register.",
        "C.ADD"      => "Compressed add.",
        "C.JR"       => "Compressed jump register.",
        "C.JALR"     => "Compressed jump-and-link register.",
        "C.J"        => "Compressed unconditional jump.",
        "C.JAL"      => "Compressed jump and link (RV32 only).",
        "C.BEQZ"     => "Compressed branch if rs1' == 0.",
        "C.BNEZ"     => "Compressed branch if rs1' != 0.",
        "C.LWSP"     => "Compressed load word from stack.",
        "C.SWSP"     => "Compressed store word to stack.",
        "C.LW"       => "Compressed load word.",
        "C.SW"       => "Compressed store word.",
        "C.EBREAK"   => "Compressed environment breakpoint.",
        "C.ADDI4SPN" => "Compressed add 4*nzuimm to sp into rd' (stack-frame setup).",
        // Vector — show a few; the rest fall through to the generic note
        "vsetvli"   => "Configure vector length, SEW, LMUL, tail-/mask-agnostic flags from immediate type.",
        "vsetivli"  => "vsetvl with vl coming from a 5-bit immediate.",
        "vsetvl"    => "Configure vector context from rs1 (vl) and rs2 (vtype).",
        _ => return None,
    })
}
